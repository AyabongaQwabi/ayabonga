import assert from "node:assert/strict";
import fs from "node:fs/promises";
import { chromium } from "playwright";
const base = process.env.SAMSUNG_TEST_BASE_URL || "http://127.0.0.1:5191";
const browser = await chromium.launch({ headless: true, channel: "chrome" });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: "reduce", acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(`${base}/samsung-intents`);
  await page.getByRole("heading", { name: "Activity manager", exact: true }).waitFor();
  await page.getByLabel("Activity group", { exact: true }).selectOption("samsung-section-connections");
  const wifi = page.locator('[data-shortcut-id="action_wifi_settings"]');
  const bluetooth = page.locator('[data-shortcut-id="action_bluetooth_settings"]');
  await wifi.getByRole("button", { name: "Wrong screen", exact: true }).click();
  await bluetooth.getByRole("button", { name: "Worked", exact: true }).click();
  await page.getByRole("button", { name: "1 Needs review", exact: true }).click();
  assert.equal(await page.locator(".sl-card").count(), 1);
  await page.getByRole("button", { name: "Compact view", exact: true }).click();
  await page.getByLabel("Sort activities", { exact: true }).selectOption("name");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export 1 as CSV", exact: true }).click();
  const download = await downloadPromise;
  const csv = await fs.readFile(await download.path(), "utf8");
  assert.ok(csv.includes('"Wi-Fi"'));
  assert.ok(csv.includes('"failed"'));
  assert.ok(!csv.includes('"Bluetooth settings"'));
  // Session ends; confirmed outcomes come back from the durable local log.
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.getByRole("heading", { name: "Activity manager", exact: true }).waitFor();
  assert.equal(await page.locator(".sl-compact").count(), 1);
  assert.equal(await page.getByLabel("Sort activities", { exact: true }).inputValue(), "name");
  await page.getByRole("button", { name: "1 Needs review", exact: true }).click();
  assert.equal(await page.locator(".sl-card-failed").count(), 1);
  await page.getByRole("button", { name: "Reset failure marks", exact: true }).click();
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.getByRole("heading", { name: "Activity manager", exact: true }).waitFor();
  await page.getByRole("button", { name: "0 Needs review", exact: true }).click();
  assert.equal(await page.locator(".sl-card-failed").count(), 0);
  await page.getByRole("button", { name: "1 Confirmed working", exact: true }).click();
  assert.equal(await page.locator(".sl-card-worked").count(), 1);
  await page.getByRole("button", { name: "Untested", exact: true }).click();
  assert.equal(await page.locator(".sl-card-worked").count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole("button", { name: "Manage an app", exact: true }).click();
  await page.locator(".sl-manager-overview button").first().click();
  assert.equal(await page.getByLabel("Activity group", { exact: true }).inputValue(), "all");
  await page.reload();
  await page.getByRole("heading", { name: "Activity manager", exact: true }).waitFor();
  assert.equal(await page.getByLabel("Activity group", { exact: true }).inputValue(), "all");
  assert.deepEqual(errors, []);
  await page.screenshot({ path: "/tmp/samsung-activity-manager-mobile.png", fullPage: false });
  console.log(JSON.stringify({ mobile: true, filters: true, csv: true, durableResults: true, clearedResults: true, preferences: true, pageErrors: errors }));
} finally { await browser.close(); }
